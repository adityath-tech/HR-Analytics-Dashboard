import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv("/content/HR-Employee-Attrition.csv")
print(df.head())

print(df.isnull().sum())
print("Duplicates:", df.duplicated().sum())

df.drop_duplicates(inplace=True)

print(df.shape)
print(df.info())
print(df.describe())
print(df.columns)

print(df['Attrition'].value_counts())

print(df.groupby('Department')['Attrition'].value_counts())

print(df.groupby('Attrition')['MonthlyIncome'].mean())

print(df.groupby('OverTime')['Attrition'].value_counts())

print(df.groupby('JobRole')['Attrition'].value_counts())

sns.histplot(data=df, x='Age', hue='Attrition', kde=True)
plt.title("Age Distribution")
plt.show()

sns.boxplot(data=df, x='Attrition', y='MonthlyIncome')
plt.title("Salary vs Attrition")
plt.show()

print("Attrition:", round((df.Attrition=='Yes').mean()*100,2), "%")
print(df.groupby('OverTime').Attrition.value_counts())

